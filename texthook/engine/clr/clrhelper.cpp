bool GetDotNetMethodAddress(
    const wchar_t* assemblyName,
    const wchar_t* typeName,
    const wchar_t* methodName,
    int parameterCount,
    void** outAddress
) {
    if (!outAddress) return false;
    *outAddress = nullptr;

    HRESULT hr;
    ICLRMetaHost* pMetaHost = nullptr;
    ICLRRuntimeInfo* pRuntimeInfo = nullptr;
    ICLRRuntimeHost* pClrHost = nullptr;
    bool success = false;

    void* methodJitAddrResult = nullptr;
    unsigned long long rawOutputMemoryAddress = (unsigned long long)&methodJitAddrResult;

    hr = CLRCreateInstance(CLSID_CLRMetaHost, IID_PPV_ARGS(&pMetaHost));
    if (FAILED(hr)) return false;

    hr = pMetaHost->GetRuntime(L"v4.0.30319", IID_PPV_ARGS(&pRuntimeInfo));
    if (FAILED(hr)) {
        pMetaHost->Release();
        return false;
    }

    BOOL isLoadable = FALSE;
    hr = pRuntimeInfo->IsLoadable(&isLoadable);
    if (FAILED(hr) || !isLoadable) {
        pRuntimeInfo->Release();
        pMetaHost->Release();
        return false;
    }

    hr = pRuntimeInfo->GetInterface(CLSID_CLRRuntimeHost, IID_PPV_ARGS(&pClrHost));
    if (FAILED(hr)) {
        pRuntimeInfo->Release();
        pMetaHost->Release();
        return false;
    }

    hr = pClrHost->Start();
    if (FAILED(hr) && hr != S_FALSE) {
        pClrHost->Release();
        pRuntimeInfo->Release();
        pMetaHost->Release();
        return false;
    }

    wchar_t modulePath[MAX_PATH];
    GetModuleFileNameW(nullptr, modulePath, MAX_PATH);
    std::wstring helperPath = modulePath;
    size_t pos = helperPath.find_last_of(L"\\/");
    if (pos != std::wstring::npos) {
        helperPath = helperPath.substr(0, pos + 1);
    }
    helperPath += L"CLRHelper.dll";

    std::wstringstream argStream;
    argStream << assemblyName << L"|" << typeName << L"|" << methodName << L"|"
              << parameterCount << L"|" << rawOutputMemoryAddress;
    std::wstring argument = argStream.str();

    DWORD returnValue = 0;

    hr = pClrHost->ExecuteInDefaultAppDomain(
        helperPath.c_str(),
        L"CLRHelper.JitHelper",
        L"GetMethodJitAddress",
        argument.c_str(),
        &returnValue
    );

    if (SUCCEEDED(hr) && returnValue == 1 && methodJitAddrResult != nullptr) {
        *outAddress = methodJitAddrResult;
        success = true;
    }

    if (pClrHost) pClrHost->Release();
    if (pRuntimeInfo) pRuntimeInfo->Release();
    if (pMetaHost) pMetaHost->Release();

    return success;
}

bool ExecuteManagedCode(
    ICLRRuntimeHost* pClrHost,
    const wchar_t* assemblyPath,
    const wchar_t* typeName,
    const wchar_t* methodName,
    const wchar_t* argument,
    DWORD* returnValue
) {
    if (!pClrHost) return false;
    HRESULT hr = pClrHost->ExecuteInDefaultAppDomain(assemblyPath, typeName, methodName, argument, returnValue);
    return SUCCEEDED(hr);
}

