bool ExtractHelperAssembly(const wchar_t* extractPath) {
    if (!extractPath) return false;

    if (Util::CheckFile(L"CLRHelper.dll")) {
        return true;
    }

    std::ofstream outFile(extractPath, std::ios::out | std::ios::binary | std::ios::trunc);

    if (!outFile.is_open()) {
        std::wstring pathStr(extractPath);
        size_t pos = pathStr.find_last_of(L"\\/");
        if (pos != std::wstring::npos) {
            std::wstring dirPath = pathStr.substr(0, pos);
            if (GetFileAttributesW(dirPath.c_str()) == INVALID_FILE_ATTRIBUTES) {
                CreateDirectoryW(dirPath.c_str(), nullptr);
            }
        }

        outFile.open(extractPath, std::ios::out | std::ios::binary | std::ios::trunc);
    }

    if (outFile.is_open()) {
        outFile.write(reinterpret_cast<const char*>(data), sizeof(data));
        outFile.close();
        return true;
    }

    return false;
}

